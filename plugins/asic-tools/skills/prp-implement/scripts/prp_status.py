#!/usr/bin/env python3
"""PRP status standard, linter and registry generator.

THE STANDARD
------------
A PRP's ``**Status:**`` header line carries exactly one of five values. Free prose may follow an
em dash (`` — ``); it is captured and never linted, because three real PRPs use it to record gate
waivers and validation evidence.

===========================  ==============================  ==========================
Value                        Written by                      Means
===========================  ==============================  ==========================
Draft                        prp-draft at close              Written, not hardened.
Ready for execution          prp-review on a clean round     The only state prp-implement
                                                             A2 starts from.
Implemented (YYYY-MM-DD)     prp-implement Phase C           Every gate met. Date required.
Blocked                      a human                         Deferred; the note should name
                                                             what unblocks it.
Superseded (by PRP-NNN)      a human                         Successor required.
===========================  ==============================  ==========================

``In progress`` is deliberately absent. prp-implement A2 detects an in-flight run from the
existence of a ``feature/prp-NNN-slug`` branch, and A2.5 treats the branch commit log as the
authority on which tasks are done. Storing it would be a second, weaker source of truth for
something git answers exactly -- and it would break resume, because A2's precondition is
``Status`` = ``Ready for execution``. The registry derives an in-flight badge at render time
instead, and stores nothing.

EXIT CODES
----------
0  every PRP conformant
1  a violation -- a status the standard does not allow, a missing date or successor, a header
   with no Status line, or a corpus-integrity breach (mis-named file, duplicate designator)
2  usage error -- bad path, empty corpus, or a STATUS.md without the generated banner
3  indeterminate -- a PRP file is a symlink resolving outside the scanned directory, so it could
   not safely be read

A violation always beats an indeterminate. An absent required field is a violation, never an
indeterminate: reporting a PRP with no status as "the parser might be at fault" is a false accept.
"""

from __future__ import annotations

import argparse
import dataclasses
import logging
import os
import re
import subprocess
import sys
import tempfile
from collections import Counter
from dataclasses import dataclass
from datetime import date
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stderr)
logger = logging.getLogger(__name__)

BANNER = "<!-- generated by prp_status.py; do not edit -- re-run the script with --write -->"
EM_DASH = " — "
PRP_FILENAME = re.compile(r"^PRP-(\d{3}[a-z]?)_.+\.md$")
# Reason: the designator is three digits plus an OPTIONAL lowercase letter, and uniqueness is
# keyed on the whole thing. A split parent and its children (PRP-058, 058a, 058b, 058c) are
# distinct PRPs with their own rows; only a repeated full designator is a duplicate. Keying on
# the digits alone made every lettered child collide with its parent and be dropped from the
# registry unlinted -- 13 of Airi's 77 -- which is the silent drop this rule exists to prevent.
STATUS_KEY = re.compile(r"^\*\*Status:\*\*\s*(.*)$")
BRANCH_KEY = re.compile(r"^\*\*Branch:\*\*\s*(.*)$")
ANY_BOLD_KEY = re.compile(r"^\*\*[^*]+:\*\*")
NON_CORPUS = {"STATUS.md", "README.md"}

KINDS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("Draft", re.compile(r"Draft")),
    ("Ready for execution", re.compile(r"Ready for execution")),
    ("Implemented", re.compile(r"Implemented \((\d{4}-\d{2}-\d{2})\)")),
    ("Blocked", re.compile(r"Blocked")),
    ("Superseded", re.compile(r"Superseded \(by (PRP-\d{3}[a-z]?)\)")),
)

GLYPHS = {
    "Draft": "\U0001f4cb",
    "Ready for execution": "\U0001f7e1",
    "Implemented": "✅",
    "Blocked": "⏸",
    "Superseded": "\U0001f5c2",
}


class HeaderError(ValueError):
    """The header block could not be bounded: no ``---`` line and no ``## `` heading."""


@dataclass(frozen=True)
class PrpRow:
    """One PRP's parsed header, and the verdict on it."""

    number: str
    rel_path: str
    title: str
    raw_status: str
    kind: str | None
    date: str | None
    successor: str | None
    note: str
    branch: str | None
    in_flight: bool
    problem: str | None


@dataclass
class Report:
    """Accumulated result of one scan. Exit precedence is applied in ``main``, not here."""

    rows: list[PrpRow]
    violations: list[str]
    limitations: list[str]
    warnings: list[str]


def header_block(text: str) -> str:
    """Return the header block: everything before the first ``---`` or ``## `` line.

    Args:
        text: Full file contents.

    Returns:
        The header block, newline-joined.

    Raises:
        HeaderError: Neither boundary appears in the file.
    """
    out: list[str] = []
    for line in text.splitlines():
        if line.strip() == "---" or line.startswith("## "):
            return "\n".join(out)
        out.append(line)
    raise HeaderError("no `---` line and no `## ` heading: not PRP-shaped")


def _first_keyed_value(block: str, key: re.Pattern[str]) -> str | None:
    """Return the first value for ``key`` in ``block``, joining one wrapped continuation line.

    A continuation is joined when the next line is non-blank, opens no new bold key, and is not a
    heading or list item. The terminator is any bold key, not a whitelist, so a future header
    field cannot be swallowed into the value.
    """
    lines = block.splitlines()
    for i, line in enumerate(lines):
        match = key.match(line)
        if not match:
            continue
        value = match.group(1).strip()
        for nxt in lines[i + 1 :]:
            stripped = nxt.strip()
            if not stripped or ANY_BOLD_KEY.match(nxt) or nxt.startswith(("#", "-", "*", "|")):
                break
            value = f"{value} {stripped}"
        return value
    return None


def find_status(block: str) -> str | None:
    """Return the first ``**Status:**`` value in the header block, or None."""
    return _first_keyed_value(block, STATUS_KEY)


def find_branch(block: str) -> str | None:
    """Return the first ``**Branch:**`` value, stripped of whitespace and inline-code backticks.

    Every real PRP stores this backtick-wrapped, so an unstripped value never equals a git ref.
    """
    raw = _first_keyed_value(block, BRANCH_KEY)
    return raw.strip().strip("`").strip() or None if raw else None


def find_title(block: str, path: Path) -> str:
    """Return the row title: the header H1 minus its ``PRP-NNN:`` prefix, else the filename stem."""
    for line in block.splitlines():
        if line.startswith("# "):
            title = line[2:].strip()
            return re.sub(r"^PRP-\d{3}[a-z]?\s*[:—-]\s*", "", title).strip() or path.stem
    return path.stem


def classify(raw: str) -> tuple[str | None, str | None, str | None, str]:
    """Classify a raw status value.

    Splits at the first em dash and full-matches the prefix against the enum. The date is checked
    for calendar validity as well as shape: ``Implemented (2026-00-00)`` is regex-valid and not a
    date.

    Returns:
        ``(kind, date, successor, note)``. ``kind`` is None when non-conforming.
    """
    prefix, _, note = raw.partition(EM_DASH)
    prefix = prefix.strip()
    for name, pattern in KINDS:
        match = pattern.fullmatch(prefix)
        if not match:
            continue
        if name == "Implemented":
            stamp = match.group(1)
            try:
                date.fromisoformat(stamp)
            except ValueError:
                return None, None, None, note.strip()
            return name, stamp, None, note.strip()
        if name == "Superseded":
            return name, None, match.group(1), note.strip()
        return name, None, None, note.strip()
    return None, None, None, note.strip()


def _problem_for(raw: str) -> str:
    """Return the violation text for a non-conforming status, naming the nearest rule."""
    prefix = raw.partition(EM_DASH)[0].strip()
    if prefix.startswith("Implemented"):
        return f"missing or invalid date on Implemented: {prefix!r}"
    if prefix.startswith("Superseded"):
        return f"missing successor on Superseded: {prefix!r}"
    return f"non-conforming status: {prefix!r}"


def check_prp(path: Path, rel: str, numbers: set[str], report: Report) -> None:
    """Parse one PRP and append its row, plus any violation, to ``report``."""
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        report.violations.append(f"{rel}: unreadable ({exc})")
        return

    number = PRP_FILENAME.match(path.name).group(1)  # caller guarantees the match
    try:
        block = header_block(text)
    except HeaderError as exc:
        report.violations.append(f"{rel}: {exc}")
        report.rows.append(_invalid_row(number, rel, path.stem, "", "unbounded header"))
        return

    title = find_title(block, path)
    raw = find_status(block)
    if raw is None:
        # An absent required field is a violation, never indeterminate (see module docstring).
        report.violations.append(f"{rel}: no `**Status:**` line in the header block")
        report.rows.append(_invalid_row(number, rel, title, "", "no Status line"))
        return

    kind, stamp, successor, note = classify(raw)
    problem = None if kind else _problem_for(raw)
    if kind == "Superseded":
        problem = _successor_problem(number, successor, numbers)
    if problem:
        report.violations.append(f"{rel}: {problem}")

    report.rows.append(
        PrpRow(
            number=number,
            rel_path=rel,
            title=title,
            raw_status=raw,
            kind=kind if not problem else None,
            date=stamp,
            successor=successor,
            note=note,
            branch=find_branch(block),
            in_flight=False,
            problem=problem,
        )
    )


def _successor_problem(number: str, successor: str | None, numbers: set[str]) -> str | None:
    """Return the violation text when a Superseded pointer is self-referential or dangling."""
    if successor == f"PRP-{number}":
        return f"Superseded by itself: {successor}"
    if successor and successor[4:] not in numbers:
        return f"successor does not exist: {successor}"
    return None


def _invalid_row(number: str, rel: str, title: str, raw: str, problem: str) -> PrpRow:
    """Build a row for a PRP that could not be classified."""
    return PrpRow(number, rel, title, raw, None, None, None, "", None, False, problem)


def iter_prps(root: Path, report: Report) -> list[Path]:
    """Return the PRP files under ``root``, recording corpus-integrity violations.

    Non-recursive. Sweeps every ``*.md`` so a mis-named file is a loud violation rather than a
    silent drop -- the glob is exactly the filter that would make it disappear. Symlinks resolving
    outside ``root`` are skipped and recorded as limitations, never read.
    """
    root = root.resolve()
    kept: list[Path] = []
    seen: dict[str, str] = {}
    for entry in sorted(root.iterdir()):
        if entry.suffix != ".md" or entry.name in NON_CORPUS:
            continue
        resolved = entry.resolve()
        if not resolved.is_relative_to(root):
            report.limitations.append(f"{entry.name}: symlink resolves outside {root}")
            continue
        match = PRP_FILENAME.match(entry.name)
        if not match:
            report.violations.append(f"{entry.name}: does not match PRP-NNN_NAME.md")
            continue
        number = match.group(1)
        if number in seen:
            report.violations.append(
                f"{entry.name}: duplicate designator {number} (also {seen[number]})"
            )
            continue
        seen[number] = entry.name
        kept.append(resolved)
    return kept


def in_flight(rows: list[PrpRow], root: Path) -> tuple[dict[str, bool], str | None]:
    """Map PRP number to in-flight state, derived from live git refs.

    A row is in flight when its status is ``Ready for execution`` and its ``**Branch:**`` value
    matches a local or remote ref. Remote refs carry a remote segment, so each namespace is
    stripped separately -- a single global strip would turn ``refs/heads/feature/x`` into ``x``.

    Returns:
        ``(mapping, warning)``. The warning is non-None when git could not be consulted; the badge
        is decoration, so a failure here never moves the exit code.
    """
    wanted = {r.number: r.branch for r in rows if r.kind == "Ready for execution" and r.branch}
    if not wanted:
        return {}, None
    refs: set[str] = set()
    try:
        for namespace, strip in (("refs/heads", 2), ("refs/remotes", 3)):
            out = subprocess.run(
                ["git", "for-each-ref", f"--format=%(refname:lstrip={strip})", namespace],
                cwd=root,
                capture_output=True,
                text=True,
                check=True,
            )
            refs.update(line.strip() for line in out.stdout.splitlines() if line.strip())
    except (FileNotFoundError, subprocess.CalledProcessError) as exc:
        return {}, f"in-flight badge unavailable ({exc}); badges suppressed"
    return {num: branch in refs for num, branch in wanted.items()}, None


def scan(root: Path) -> Report:
    """Parse every PRP under ``root`` once, then fold in the in-flight badges."""
    report = Report(rows=[], violations=[], limitations=[], warnings=[])
    paths = iter_prps(root, report)
    numbers = {PRP_FILENAME.match(p.name).group(1) for p in paths}
    for path in paths:
        check_prp(path, path.name, numbers, report)

    badges, warning = in_flight(report.rows, root)
    if warning:
        report.warnings.append(warning)
    if badges:
        report.rows = [
            dataclasses.replace(row, in_flight=badges.get(row.number, False)) for row in report.rows
        ]
    return report


def render_status_md(report: Report) -> str:
    """Render the registry: banner, derived counts, legend, and one row per PRP.

    Three columns, not the four a hand-written registry may carry -- a "what it does" column is a
    human summary and cannot be derived from front matter.
    """
    rows = sorted(report.rows, key=lambda r: r.number)
    counts = Counter("INVALID" if r.problem else (r.kind or "INVALID") for r in rows)
    order = [name for name, _ in KINDS] + ["INVALID"]
    summary = " | ".join(f"**{k}:** {counts[k]}" for k in order if counts[k])
    flying = sum(1 for r in rows if r.in_flight)
    if flying:
        summary += f" | **in flight:** {flying}"

    lines = [
        BANNER,
        "",
        "# PRP Status Registry",
        "",
        f"**Total PRPs:** {len(rows)} | {summary}",
        "",
        "**Legend:** " + " · ".join(f"{GLYPHS[n]} {n}" for n, _ in KINDS),
        "",
        "| PRP | Title | Status |",
        "|-----|-------|--------|",
    ]
    for row in rows:
        if row.problem:
            status = f"⚠ INVALID — `{row.raw_status}`"
        else:
            status = f"{GLYPHS[row.kind]} {row.raw_status}"
            if row.in_flight:
                status += " · in flight"
        lines.append(f"| {row.number} | [{row.title}]({row.rel_path}) | {status} |")
    return "\n".join(lines) + "\n"


def write_status_md(root: Path, body: str) -> int:
    """Write STATUS.md atomically, refusing to clobber a file that is not ours.

    The banner is the consent token: a registry without it may be hand-authored and carry columns
    this script does not produce.
    """
    target = root / "STATUS.md"
    if target.exists() and BANNER not in target.read_text(encoding="utf-8").splitlines()[0:1]:
        logger.error("FAIL  %s exists without the generated banner; refusing to overwrite", target)
        return 2
    handle, tmp = tempfile.mkstemp(dir=root, suffix=".tmp")
    with os.fdopen(handle, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.replace(tmp, target)
    return 0


def main(argv: list[str] | None = None) -> int:
    """Lint every PRP under the given directory, and optionally regenerate STATUS.md."""
    parser = argparse.ArgumentParser(description="Lint PRP statuses and render the registry.")
    parser.add_argument("prps_dir", help="directory holding PRP-NNN_NAME.md files")
    parser.add_argument("--write", action="store_true", help="write STATUS.md into that directory")
    args = parser.parse_args(argv)

    try:
        root = Path(args.prps_dir).resolve(strict=True)
    except OSError as exc:
        logger.error("FAIL  %s", exc)
        return 2
    if not root.is_dir():
        logger.error("FAIL  %s is not a directory", root)
        return 2
    if not [p for p in root.iterdir() if p.suffix == ".md" and p.name not in NON_CORPUS]:
        logger.error("FAIL  %s holds no PRP markdown; refusing to write an empty registry", root)
        return 2

    report = scan(root)
    for text in report.violations:
        logger.error("FAIL  %s", text)
    for text in report.limitations:
        logger.error("LIMIT %s", text)
    for text in report.warnings:
        logger.error("WARN  %s", text)

    body = render_status_md(report)
    if args.write:
        refused = write_status_md(root, body)
        if refused:
            return refused
    else:
        sys.stdout.write(body)

    if report.violations:
        return 1
    if report.limitations:
        return 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
